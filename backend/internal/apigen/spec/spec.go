// MCP is the configuration of the MCP tools' structured outputs that the
// MCP Apps view draws
func MCP() (apigen.Config, error) {
	outputs := mcpserver.AppOutputs()
	byName := map[string]any{}
	roots := make([]apigen.Root, len(outputs))
	for i, out := range outputs {
		byName[reflect.TypeOf(out).Name()] = out
		roots[i] = apigen.Root{Value: out}
	}
	for _, name := range []string{"usageSummaryOut", "queryMetricsOut", "getTraceOut", "listSessionsOut"} {
		if byName[name] == nil {
			return apigen.Config{}, fmt.Errorf("mcpserver.AppOutputs has no %s", name)
		}
	}
	return apigen.Config{
		Roots: roots,
		Names: map[string]string{
			"mcpserver.usageSummaryOut": "UsageSummary",
			"mcpserver.usageRow":        "UsageRow",
			"mcpserver.queryMetricsOut": "MetricsResult",
			"mcpserver.seriesOut":       "MetricSeries",
			"mcpserver.pointOut":        "MetricPoint",
			"mcpserver.getTraceOut":     "TraceResult",
			"mcpserver.spanOut":         "TraceSpan",
			"mcpserver.listSessionsOut": "SessionsResult",
			"mcpserver.sessionOut":      "SessionRow",
		},
		Enums: []apigen.EnumSpec{
			{Name: "UsageGroup", Values: mcpserver.UsageGroups, Doc: "What usage_summary groups costs and tokens by"},
			metricTypeEnum,
			histogramStatEnum,
		},
		Fields: []apigen.FieldSpec{
			{Type: byName["usageSummaryOut"], Field: "GroupBy", Enum: "UsageGroup"},
			{Type: byName["queryMetricsOut"], Field: "MetricType", Enum: "MetricType"},
			{Type: byName["queryMetricsOut"], Field: "Stat", Enum: "HistogramStat"},
			// Lists the tools build from empty slices (tested by the
			// server's TestMCPOutputsMatchTypes)
			{Type: byName["usageSummaryOut"], Field: "Rows", NonNull: true},
			{Type: byName["queryMetricsOut"], Field: "Series", NonNull: true},
			{Type: fieldElem(byName["queryMetricsOut"], "Series"), Field: "Points", NonNull: true},
			{Type: byName["getTraceOut"], Field: "Spans", NonNull: true},
			{Type: byName["listSessionsOut"], Field: "Sessions", NonNull: true},
		},
	}, nil
}

// Files returns the generated files by their path relative to the
// repository root; dir is a directory of the backend module
func Files(dir string) (map[string][]byte, error) {
	rest, err := apigen.Build(REST(), dir)
	if err != nil {
		return nil, fmt.Errorf("REST types: %w", err)
	}
	mcpConfig, err := MCP()
	if err != nil {
		return nil, err
	}
	mcp, err := apigen.Build(mcpConfig, dir)
	if err != nil {
		return nil, fmt.Errorf("MCP types: %w", err)
	}
	openapi, err := rest.OpenAPI(Routes())
	if err != nil {
		return nil, fmt.Errorf("OpenAPI: %w", err)
	}
	return map[string][]byte{
		TypeScriptFile: rest.TypeScript(header + `
The types of AI Observer's REST API and WebSocket messages (backend/internal/api,
backend/internal/websocket). Optional fields may be missing from responses;
"| null" marks values the API may send as null.`),
		MCPTypeScriptFile: mcp.TypeScript(header + `
The structured outputs of the MCP tools the MCP Apps view draws
(backend/internal/mcpserver: usage_summary, query_metrics, get_trace,
list_sessions); their fields are snake_case.`),
		OpenAPIFile: openapi,
	}, nil
}

// RepoRoot returns the repository root: the directory above the backend
// module
func RepoRoot(dir string) (string, error) {
	root, _, err := apigen.FindModuleRoot(dir)
	if err != nil {
		return "", err
	}
	return filepath.Dir(root), nil
}

// fieldElem returns the element type of a slice field of a struct value
func fieldElem(v any, field string) reflect.Type {
	f, ok := reflect.TypeOf(v).FieldByName(field)
	if !ok {
		panic(fmt.Sprintf("spec: %T has no field %s", v, field))
	}
	return f.Type.Elem()
}
